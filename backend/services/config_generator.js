const fs = require('fs');
const path = require('path');
const { isValidDomain, isPrivateIPv4, isValidPort, VALID_WAF_MODES } = require('../middleware/validator');

// Path untuk menyimpan konfigurasi Nginx yang di-generate
// Pada server Linux: default selalu /etc/nginx/panel-conf.d
// Untuk development di Windows: ./nginx-configs/
const NGINX_CONF_DIR = process.env.NGINX_CONF_DIR || (process.platform === 'linux' ? '/etc/nginx/panel-conf.d' : path.join(__dirname, '..', 'nginx-configs'));

// Pastikan folder ada
if (!fs.existsSync(NGINX_CONF_DIR)) {
  fs.mkdirSync(NGINX_CONF_DIR, { recursive: true });
}

/**
 * Pertahanan berlapis: tolak menulis config jika data proxy tidak valid
 * (mis. baris lama di database yang dibuat sebelum validasi diperketat).
 */
function assertSafeProxy(proxy) {
  if (!proxy || !isValidDomain(proxy.domain_name)) {
    throw new Error(`Domain tidak valid untuk config Nginx: ${proxy && proxy.domain_name}`);
  }
  const ip = proxy.target_ip === 'localhost' ? '127.0.0.1' : proxy.target_ip;
  if (!isPrivateIPv4(ip)) {
    throw new Error(`Target IP tidak valid untuk config Nginx: ${proxy.target_ip}`);
  }
  if (!isValidPort(Number(proxy.target_port))) {
    throw new Error(`Port tidak valid untuk config Nginx: ${proxy.target_port}`);
  }
  if (proxy.waf_mode && !VALID_WAF_MODES.includes(proxy.waf_mode)) {
    throw new Error(`Mode WAF tidak valid: ${proxy.waf_mode}`);
  }
}

function assertSafeDomain(domainName) {
  if (!isValidDomain(domainName)) {
    throw new Error(`Domain tidak valid: ${domainName}`);
  }
}

/**
 * Helper untuk menyisipkan direktif ModSecurity
 */
function getModSecDirectives(wafMode) {
  if (wafMode === 'on') {
    return `
    # ModSecurity Web Application Firewall (WAF) - Active Enforcement
    # Optimized: Nonaktifkan Response Body buffering agar streaming & TTFB super cepat
    modsecurity on;
    modsecurity_rules_file /etc/nginx/modsec/main.conf;
    modsecurity_rules 'SecRuleEngine On; SecResponseBodyAccess Off;';
`;
  } else if (wafMode === 'detection') {
    return `
    # ModSecurity Web Application Firewall (WAF) - Detection Only (Audit Log)
    # Optimized: Nonaktifkan Response Body buffering agar streaming & TTFB super cepat
    modsecurity on;
    modsecurity_rules_file /etc/nginx/modsec/main.conf;
    modsecurity_rules 'SecRuleEngine DetectionOnly; SecResponseBodyAccess Off;';
`;
  }
  return `
    # ModSecurity Web Application Firewall (WAF) - Disabled
    modsecurity off;
`;
}

/**
 * Helper untuk menyusun identifier upstream yang aman untuk Nginx
 */
function getSafeUpstreamName(domainName) {
  return (domainName || 'backend').toLowerCase().replace(/[^a-z0-9]/g, '_');
}

/**
 * Helper untuk menyusun daftar server_name termasuk alias CNAME (www <-> apex domain)
 */
function getServerNames(domainName) {
  const domain = (domainName || '').trim().toLowerCase();
  const names = [domain];

  // Jika domain diawali www., tambahkan apex domain sebagai alias
  if (domain.startsWith('www.')) {
    const apex = domain.substring(4);
    if (apex && !names.includes(apex)) {
      names.push(apex);
    }
  } else {
    // Jika bukan www (misal: ids.net.id), tambahkan www.ids.net.id sebagai alias
    const www = `www.${domain}`;
    if (!names.includes(www)) {
      names.push(www);
    }
  }

  return names.join(' ');
}

/**
 * Template konfigurasi Nginx untuk HTTP proxy (High Performance)
 */
function generateHttpConfig(proxy) {
  const modSecBlock = getModSecDirectives(proxy.waf_mode);
  const serverNames = getServerNames(proxy.domain_name);
  const upstreamName = `upstream_${getSafeUpstreamName(proxy.domain_name)}`;
  const targetIp = (proxy.target_ip === 'localhost') ? '127.0.0.1' : proxy.target_ip;

  return `# Auto-generated by Nginx Proxy Panel - High Performance HTTP
# Domain: ${proxy.domain_name}
# Server Aliases: ${serverNames}
# Created: ${proxy.created_at || new Date().toISOString()}
# WAF Mode: ${proxy.waf_mode || 'off'}

upstream ${upstreamName} {
    server ${targetIp}:${proxy.target_port} max_fails=3 fail_timeout=10s;
    keepalive 64;
}

server {
    listen 80;
    server_name ${serverNames};
${modSecBlock}
    # Logging
    access_log /var/log/nginx/${proxy.domain_name}.access.log;
    error_log /var/log/nginx/${proxy.domain_name}.error.log warn;

    client_max_body_size 100M;

    # Static Assets Caching & Acceleration (Bypass overhead & browser caching)
    location ~* \\.(?:css|js|jpg|jpeg|gif|png|ico|cur|gz|svg|svgz|mp4|ogg|ogv|webm|htc|woff|woff2|ttf|otf|eot)$ {
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        # Abaikan header anti-cache dari backend (n8n/Node.js mengirim Set-Cookie/no-cache yang membatalkan cache)
        proxy_ignore_headers Cache-Control Expires Set-Cookie;
        proxy_hide_header Set-Cookie;
        proxy_hide_header Cache-Control;

        # Local Proxy Cache di Server Panel (hanya 1x ambil dari backend on-premise, selanjutnya 0ms)
        proxy_cache PANEL_CACHE;
        proxy_cache_valid 200 304 30d;
        proxy_cache_use_stale error timeout updating http_500 http_502 http_503 http_504;
        proxy_cache_lock on;
        proxy_cache_lock_timeout 5s;
        proxy_cache_revalidate on;
        # Jangan simpan / sajikan cache untuk request yang membawa kredensial
        proxy_no_cache $http_authorization;
        proxy_cache_bypass $http_authorization;

        # Browser Cache 30 hari (Instan dari disk cache laptop)
        expires 30d;
        add_header Cache-Control "public, max-age=2592000, immutable" always;
        add_header X-Cache-Status $upstream_cache_status always;
        access_log off;
    }

    location / {
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;

        # Headers
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        # WebSocket support & Upstream Keepalive pooling
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;

        # Disable buffering untuk SSE (Server-Sent Events), n8n canvas, AI streaming
        proxy_buffering off;
        proxy_cache off;
        chunked_transfer_encoding off;

        # Timeouts panjang untuk workflow n8n & long polling
        proxy_connect_timeout 60s;
        proxy_send_timeout 3600s;
        proxy_read_timeout 3600s;
    }

    # Khusus OAuth2 Callback & Webhooks (Bypass WAF false-positives & buffering)
    location ~* ^/(rest/oauth2-credential/callback|webhook|webhook-test|webhook-waiting)(/|$) {
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;

        # Headers
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        # Disable Buffering & Cache
        proxy_buffering off;
        proxy_cache off;
        chunked_transfer_encoding off;

        # Buffer besar untuk token/header OAuth
        proxy_buffer_size 128k;
        proxy_buffers 4 256k;
        proxy_busy_buffers_size 256k;

        proxy_connect_timeout 60s;
        proxy_send_timeout 300s;
        proxy_read_timeout 300s;

        # Bypass WAF ModSecurity jika aktif agar tidak memblokir kode token acak
        ${proxy.waf_mode !== 'off' ? 'modsecurity off;' : ''}
    }
}
`;
}

